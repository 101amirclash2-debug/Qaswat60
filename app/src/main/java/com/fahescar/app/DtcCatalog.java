    private DtcCatalog() { }

    private static void put(String code, String title, String explanation) {
        DEFINITIONS.put(code, new Definition(title, explanation));
    }

    public static Definition lookup(String code) {
        Definition definition = DEFINITIONS.get(code);
        if (definition != null) return definition;
        String system;
        if (code == null || code.length() < 1) {
            system = "غير معروف";
        } else {
            switch (code.charAt(0)) {
                case 'P': system = "مجموعة نقل الحركة"; break;
                case 'C': system = "الشاسيه"; break;
                case 'B': system = "الهيكل/التجهيزات"; break;
                case 'U': system = "شبكة الاتصال"; break;
                default: system = "غير معروف";
            }
        }
        String title = "رمز " + (code == null ? "غير معروف" : code) + " — " + system;
        String explanation = "تمت قراءة هذا الرمز فعلياً من وحدة التحكم، لكن تعريفه التفصيلي غير موجود في القاموس المحلي. راجع دليل صيانة السيارة أو قاعدة بيانات الشركة المصنّعة. لا تستبدل قطعاً اعتماداً على الرمز وحده.";
        return new Definition(title, explanation);
    }
